#pragma once
/*
 * Per-SoC hardware tables behind kshim/gpio.h, kshim/pinctrl.h and
 * kshim/clk.h (owner sm8650, kernel/soc/). Pure data and lookups, no MMIO.
 *
 *  - TLMM layout: SM8150/SM8250 use the CrDK Android pin tables
 *    (CrAndroidPin, per-pin control offsets and function names); SM8650 is
 *    linear (pin * 0x1000) with the mux slots of kernel/soc/sm8650_tables.c.
 *  - Clock leaves: SM8150/SM8250 Android clock IDs through CrAndroidClock;
 *    SM8650 GCC/TCSR rows keyed by their dt-binding IDs and Linux names
 *    (kernel/soc/sm8650_tables.c, generated by tools/gen_sm8650_tables.py).
 */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* SoC numbers as kshim_dt_soc() returns them. */
#define KSHIM_SOC_SM8150 8150U
#define KSHIM_SOC_SM8250 8250U
#define KSHIM_SOC_SM8650 8650U

/* TLMM CFG register (pinctrl-msm layout, CrDK GpioLib RegCfg[0]). */
#define KSHIM_TLMM_CFG_PULL_MASK 0x3U
#define KSHIM_TLMM_CFG_FUNC_SHIFT 2U
#define KSHIM_TLMM_CFG_FUNC_MASK 0x3cU
#define KSHIM_TLMM_CFG_DRV_SHIFT 6U
#define KSHIM_TLMM_CFG_DRV_MASK 0x1c0U
#define KSHIM_TLMM_CFG_OE 0x200U
/* SM8650 EGPIO (pinctrl-sm8650 egpio_present 11 / egpio_enable 12; CrDK
 * Target/Sm8650 EgpioPresentMsk/EgpioEnabledMsk). */
#define KSHIM_TLMM_CFG_EGPIO_PRESENT 0x800U
#define KSHIM_TLMM_CFG_EGPIO_ENABLE 0x1000U
#define KSHIM_TLMM_IO_IN 0x1U
#define KSHIM_TLMM_IO_OUT 0x2U
#define KSHIM_TLMM_PIN_SPAN 0x10U

struct kshim_soc_tlmm {
    unsigned soc;
    uint16_t pins;        /* normal pins 0..pins-1 */
    bool linear;          /* control at base + pin * 0x1000 */
    bool egpio;           /* EGPIO present/enable bits exist */
};
/* Layout of a TLMM provider compatible; NULL when unknown. */
const struct kshim_soc_tlmm *kshim_soc_tlmm(unsigned soc);
/* Control-register offset of `pin` from the TLMM base; false when the pin
 * has no normal pad on this SoC. */
bool kshim_soc_pin_offset(unsigned soc, uint32_t pin, uint32_t *offset);
/* Mux slot of `function` on `pin` ("gpio" is slot 0); false when the pad
 * does not offer it. */
bool kshim_soc_pin_function(unsigned soc, uint32_t pin, const char *function, uint32_t *mux);

/* One clock-controller leaf. space: 0 clock, 1 GDSC, 2 reset. */
enum { KSHIM_SOC_CLK_SPACE_CLOCK, KSHIM_SOC_CLK_SPACE_GDSC, KSHIM_SOC_CLK_SPACE_RESET };
struct kshim_soc_clk {
    const char *name;
    uint8_t space;
    uint16_t id;
    uint8_t kind;          /* enum kshim_clk_kind */
    uint8_t halt;          /* enum kshim_clk_halt */
    uint32_t enable_reg;   /* offsets from the controller base */
    uint32_t enable_mask;
    uint32_t halt_reg;
    uint32_t rcg;
};
struct kshim_soc_clock_controller {
    const char *compatible;
    const char *label;     /* "gcc", "tcsr" for kshim_clk_get_by_name */
    unsigned soc;
    const struct kshim_soc_clk *leaves; /* NULL: CrAndroidClock(soc, id) */
    const size_t *count;
};
/* Controller table for a DT compatible; NULL when unknown. */
const struct kshim_soc_clock_controller *kshim_soc_clock_controller(const char *compatible);
const struct kshim_soc_clock_controller *kshim_soc_clock_controller_at(size_t index);
/* Leaf by id space and dt-binding id, or by Linux name (space ignored when
 * name is used). Fills *leaf (offsets) and returns true when found. */
bool kshim_soc_clock_leaf(const struct kshim_soc_clock_controller *c, uint8_t space,
                          uint32_t id, struct kshim_soc_clk *leaf);
bool kshim_soc_clock_leaf_by_name(const struct kshim_soc_clock_controller *c,
                                  const char *name, struct kshim_soc_clk *leaf);

/* Generated SM8650 data (kernel/soc/sm8650_tables.c). */
extern const char *const kshim_sm8650_pin_names[];
extern const uint8_t kshim_sm8650_pin_mux[210][10];
extern const uint16_t kshim_sm8650_pin_name_count;
extern const struct kshim_soc_clk kshim_sm8650_gcc[];
extern const size_t kshim_sm8650_gcc_count;
extern const struct kshim_soc_clk kshim_sm8650_tcsr[];
extern const size_t kshim_sm8650_tcsr_count;
