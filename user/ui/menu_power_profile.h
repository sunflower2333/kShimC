#ifndef KSHIM_MENU_POWER_PROFILE_H
#define KSHIM_MENU_POWER_PROFILE_H
/* Explicit presentation contract for every design family, including FLAT.
 * These profiles never alter the shared capability or confirmation contract. */
enum { POWER_AT_HEADER, POWER_AT_ACTIONS, POWER_AT_DETAIL, POWER_AT_DISKS,
       POWER_AT_NATIVE };
enum { POWER_MENU_FLYOUT, POWER_MENU_LIST, POWER_MENU_SHEET,
       POWER_MENU_TILES, POWER_MENU_BENTO, POWER_MENU_TYPE, POWER_MENU_NATIVE };
enum { POWER_LOOK_PLAIN, POWER_LOOK_CLASSIC, POWER_LOOK_MATERIAL2,
       POWER_LOOK_GLASS, POWER_LOOK_SOFT, POWER_LOOK_NEON, POWER_LOOK_IOS,
       POWER_LOOK_ADWAITA, POWER_LOOK_HOLO, POWER_LOOK_NORD, POWER_LOOK_METRO,
       POWER_LOOK_CARDS, POWER_LOOK_AURORA, POWER_LOOK_HARMONY, POWER_LOOK_CONTRAST };
typedef struct {
    uint8_t location, menu, look, radius, icon_entry;
    uint16_t width;
} kshim_power_profile_t;
static kshim_power_profile_t KshimPowerProfile(void)
{
#define P(at,menu,look,radius,icons,width) return (kshim_power_profile_t){at,menu,look,radius,icons,width}
    switch(mMenuDesign.kind) {
    case 0: P(POWER_AT_HEADER,POWER_MENU_FLYOUT,POWER_LOOK_PLAIN,8,1,340); /* FLAT */
    case KSHIM_DESIGN_CLASSIC: P(POWER_AT_ACTIONS,POWER_MENU_LIST,POWER_LOOK_CLASSIC,0,0,360);
    case KSHIM_DESIGN_CARDS: P(POWER_AT_ACTIONS,POWER_MENU_TILES,POWER_LOOK_CARDS,12,2,520);
    case KSHIM_DESIGN_TERMINAL: P(POWER_AT_ACTIONS,POWER_MENU_TYPE,POWER_LOOK_PLAIN,0,0,600);
    case KSHIM_DESIGN_MINIMAL: P(POWER_AT_ACTIONS,POWER_MENU_TYPE,POWER_LOOK_PLAIN,0,0,360);
    case KSHIM_DESIGN_HIGH_CONTRAST: P(POWER_AT_ACTIONS,POWER_MENU_LIST,POWER_LOOK_CONTRAST,0,0,440);
    case KSHIM_DESIGN_FLUENT: P(POWER_AT_HEADER,POWER_MENU_FLYOUT,POWER_LOOK_PLAIN,0,1,300);
    case KSHIM_DESIGN_FLUENT2: P(POWER_AT_HEADER,POWER_MENU_FLYOUT,POWER_LOOK_PLAIN,8,1,320);
    case KSHIM_DESIGN_MATERIAL2: P(POWER_AT_HEADER,POWER_MENU_LIST,POWER_LOOK_MATERIAL2,4,1,360);
    case KSHIM_DESIGN_MATERIAL3: P(POWER_AT_ACTIONS,POWER_MENU_FLYOUT,POWER_LOOK_PLAIN,28,0,320);
    case KSHIM_DESIGN_SURFACE: P(POWER_AT_DETAIL,POWER_MENU_FLYOUT,POWER_LOOK_PLAIN,2,1,340);
    case KSHIM_DESIGN_CUPERTINO: P(POWER_AT_DISKS,POWER_MENU_LIST,POWER_LOOK_PLAIN,12,0,340);
    case KSHIM_DESIGN_IOS_HIG: P(POWER_AT_HEADER,POWER_MENU_SHEET,POWER_LOOK_IOS,14,1,390);
    case KSHIM_DESIGN_HARMONYOS: P(POWER_AT_ACTIONS,POWER_MENU_TILES,POWER_LOOK_HARMONY,24,2,520);
    case KSHIM_DESIGN_CLOVER: P(POWER_AT_DISKS,POWER_MENU_TILES,POWER_LOOK_PLAIN,12,1,480);
    case KSHIM_DESIGN_GLASS: P(POWER_AT_HEADER,POWER_MENU_FLYOUT,POWER_LOOK_GLASS,20,1,360);
    case KSHIM_DESIGN_AURORA: P(POWER_AT_ACTIONS,POWER_MENU_TILES,POWER_LOOK_AURORA,24,2,500);
    case KSHIM_DESIGN_SOFT_UI: P(POWER_AT_ACTIONS,POWER_MENU_LIST,POWER_LOOK_SOFT,20,2,390);
    case KSHIM_DESIGN_BENTO: P(POWER_AT_ACTIONS,POWER_MENU_BENTO,POWER_LOOK_CARDS,20,2,480);
    case KSHIM_DESIGN_NEON: P(POWER_AT_HEADER,POWER_MENU_LIST,POWER_LOOK_NEON,0,1,420);
    case KSHIM_DESIGN_NORD: P(POWER_AT_ACTIONS,POWER_MENU_FLYOUT,POWER_LOOK_NORD,6,0,360);
    case KSHIM_DESIGN_METRO: P(POWER_AT_ACTIONS,POWER_MENU_TYPE,POWER_LOOK_METRO,0,0,480);
    case KSHIM_DESIGN_ADWAITA: P(POWER_AT_HEADER,POWER_MENU_FLYOUT,POWER_LOOK_ADWAITA,12,1,340);
    case KSHIM_DESIGN_HOLO: P(POWER_AT_HEADER,POWER_MENU_LIST,POWER_LOOK_HOLO,0,1,360);
    case KSHIM_DESIGN_LVGL_DEFAULT: P(POWER_AT_NATIVE,POWER_MENU_NATIVE,POWER_LOOK_PLAIN,0,1,340);
    default: return (kshim_power_profile_t){0}; /* A missing family fails the contract test. */
    }
#undef P
}
#endif
